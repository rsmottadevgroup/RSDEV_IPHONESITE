export const formatPrice = (price) => {
  return new Intl.NumberFormat('pt-BR', {
    style: 'currency',
    currency: 'BRL'
  }).format(price);
};

export const calculateInstallment = (price, times = 12) => {
  return formatPrice(price / times);
};
